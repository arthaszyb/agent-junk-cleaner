#!/usr/bin/env python3
"""Render docs/catalog.md from the rule catalog (all four domains on, default settings).

    python3 scripts/gen_catalog_doc.py > docs/catalog.md

tests/test_docs.py fails when the committed file differs from this output, so a rule change and its
documentation land together."""
from __future__ import annotations

import sys
from pathlib import Path
from typing import List

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'src'))

from disk_steward import i18n  # noqa: E402
from disk_steward.catalog import load_catalog  # noqa: E402
from disk_steward.model import Domain, Rule, Tier  # noqa: E402
from disk_steward.settings import Settings  # noqa: E402

TIER_ORDER = {Tier.JUNK: 0, Tier.REVIEW: 1, Tier.PROTECTED: 2}
DOMAIN_TITLES = {
    Domain.AGENT: 'AI agents (`agent`)',
    Domain.APP_LIBRARY: 'Apps and Library (`app-library`)',
    Domain.USER_FILES: 'Your files (`user-files`)',
    Domain.DEV_SHARED: 'Shared developer data (`dev-shared`)',
}
DOMAIN_NOTES = {
    Domain.AGENT: 'On by default. Includes the protections that apply everywhere (`prot.*`).',
    Domain.APP_LIBRARY: 'On by default.',
    Domain.USER_FILES: 'Off by default. Scans the folders in the `user_roots` setting.',
    Domain.DEV_SHARED: 'Off by default and report only: no rule here has an action, and the hint is the native command that cleans the store.',
}


def num(value: float) -> str:
    return f'{value:g}'


def cell(text: str) -> str:
    return text.replace('|', '\\|')


def code_list(items) -> str:
    return ', '.join(f'`{i}`' for i in items)


def actions_of(rule: Rule) -> str:
    if not rule.actions:
        return 'none'
    rest = [a.value for a in rule.actions if a != rule.default_action]
    return ', '.join([rule.default_action.value] + rest)


def table_row(rule: Rule) -> str:
    floor = num(rule.min_age_floor_days) if rule.min_age_floor_days else '-'
    default = num(rule.default_min_age_days) if rule.default_min_age_days is not None else '-'
    cells = [f'`{rule.id}`', rule.tier.value, rule.kind.value, rule.unit.value, actions_of(rule), floor, default,
             rule.age_basis.value.replace('_', ' '), str(rule.priority), f'`{rule.detector}`' if rule.detector else '-']
    return '| ' + ' | '.join(cell(c) for c in cells) + ' |'


def detail(rule: Rule, en) -> List[str]:
    lines = [f'- `{rule.id}`: {en[rule.label_key]}. {en[rule.effect_key]}']
    if rule.quit_apps:
        lines.append(f'  Quit first: {code_list(rule.quit_apps)}.')
    filters = []
    if rule.name_include:
        filters.append('names ' + code_list(rule.name_include))
    if rule.name_exclude:
        filters.append('excluding names ' + code_list(rule.name_exclude))
    if rule.min_size:
        filters.append(f'size at least {rule.min_size} bytes')
    if rule.group_depth is not None:
        filters.append(f'one group per first {rule.group_depth} path segments')
    if filters:
        lines.append('  Only ' + '; '.join(filters) + '.')
    lines.append('  Matches ' + code_list(rule.patterns) + '.')
    if rule.hint:
        lines.append(f'  Hint shown to the user: `{rule.hint}`')
    return lines


def render() -> str:
    en = i18n.catalog('en')
    catalog = load_catalog(Settings(domains=tuple(d.value for d in Domain)))
    out = [
        '# Catalog reference',
        '',
        '<!-- Generated by scripts/gen_catalog_doc.py. Do not edit; run it and commit the result. -->',
        '',
        f'{len(catalog.rules)} rules, all four domains on, default settings. A rule decides what a path is, never '
        'whether it is removed: that takes your selection and the executor\'s checks (see `safety.md`). '
        'Rules are tried by descending priority and the first match wins; a detector can refine the match at scan time.',
        '',
        'Columns: floor is the rule\'s minimum age in days, which no filter or "Include anyway" can lower. '
        'Filter is the age the rule pre-fills for its group. Age basis `last used` takes the later of the file\'s '
        'change time and Spotlight\'s last-used date. Rows are ordered junk, review, protected, then by priority.',
    ]
    for domain in Domain:
        rules = sorted((r for r in catalog.rules if r.domain == domain),
                       key=lambda r: (TIER_ORDER[r.tier], -r.priority, r.id))
        roots = [r.path for r in catalog.roots if r.domain == domain]
        out += ['', f'## {DOMAIN_TITLES[domain]}', '', f'{DOMAIN_NOTES[domain]} {len(rules)} rules.', '',
                '| Rule | Tier | Kind | Unit | Actions | Floor | Filter | Age basis | Priority | Detector |',
                '|---|---|---|---|---|---|---|---|---|---|']
        out += [table_row(r) for r in rules]
        out += ['', 'Scan roots: ' + code_list(roots) + '.', '', '### Rules in detail', '']
        for rule in rules:
            out += detail(rule, en)
    out += ['', '## Never opened', '',
            'A scan never lists, stats or opens these locations. They are protected by macOS or private by nature, '
            'so touching them would raise a permission prompt or read personal content. They are counted as '
            'skipped for privacy.', '']
    out += [f'- `{p}`' for p in catalog.privacy_skip]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    sys.stdout.write(render())
